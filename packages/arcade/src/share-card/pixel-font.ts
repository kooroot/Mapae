/** Each glyph as GLYPH_HEIGHT row bitmasks, bit 4 the leftmost column. */
export const GLYPHS: ReadonlyMap<string, readonly number[]> = new Map(Object.entries(ROWS).map(([char, rows]) => {
    const lines = rows.split("|");
    if (lines.length !== GLYPH_HEIGHT || lines.some(line => line.length !== GLYPH_WIDTH)) throw new Error(`Malformed glyph ${char}`);
    return [char, lines.map(line => [...line].reduce((mask, cell) => (mask << 1) | (cell === "#" ? 1 : 0), 0))];
}));

export const glyphOf = (char: string): readonly number[] | undefined => GLYPHS.get(char.toUpperCase());
/** Pixel width of `text` at `scale`: one advance per character, without the last gap. */
export const textWidth = (text: string, scale: number): number => text.length ? (text.length * GLYPH_ADVANCE - 1) * scale : 0;
